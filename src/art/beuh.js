// Plante en pot (3 stades : 0 pousse, 1 feuillage, 2 mûre lumineuse)
export function beuhPlantSvg(strainId, stage) {
    const s = BEUH_STRAINS[strainId] || BEUH_STRAINS.rondpoint;
    const pot =
        SHADOW(32, 59, 18, 2.8) +
        P('M18 42 L46 42 L42 57 L22 57Z', '#7c4a2d', 2.2) +
        R(15, 38, 34, 6, 2.5, '#9c5d38', 2.2) +
        E(32, 40, 14, 2.4, '#3a2418', 0, 0);
    if (stage === 0) {
        return wrap(pot + L('M32 40 Q31 32 32 27', 2.8, '#22c55e') + leaf(32, 29, 10, -145, s.col, 0.45) + leaf(32, 28, 10, -35, s.glow, 0.45));
    }
    if (stage === 1) {
        return wrap(
            pot +
                L('M32 40 L32 16', 3.2, '#166534') +
                leaf(32, 33, 15, -155, s.col, 0.32) +
                leaf(32, 33, 15, -25, s.col, 0.32) +
                leaf(32, 25, 16, -135, s.glow, 0.3) +
                leaf(32, 25, 16, -45, s.glow, 0.3) +
                leaf(32, 18, 12, -90, s.col, 0.34),
        );
    }
    // stade 2 : mûre et brillante
    return wrap(
        FE(32, 22, 20, 15, s.glow, 0.22) +
            pot +
            L('M32 40 L32 13', 3.4, '#14532d') +
            leaf(32, 34, 17, -160, s.col, 0.3) +
            leaf(32, 34, 17, -20, s.col, 0.3) +
            leaf(32, 26, 18, -140, s.col, 0.28) +
            leaf(32, 26, 18, -40, s.col, 0.28) +
            leaf(32, 18, 15, -115, s.glow, 0.28) +
            leaf(32, 18, 15, -65, s.glow, 0.28) +
            C(32, 14, 6.5, s.col, 2) +
            C(25, 22, 4.8, s.glow, 1.8) +
            C(39, 22, 4.8, s.glow, 1.8) +
            FC(30, 12, 1.8, '#fff', 0.75) +
            FC(20, 12, 1.4, s.glow, 0.9) +
            FC(45, 14, 1.6, s.glow, 0.9),
    );
}

